<?php

/**
 * `teme:docs:fields`: writes `docs/reference/fields.md` from the field
 * registry, so the reference can never drift from the code.
 *
 * @package Teme
 * @since   0.7.0-alpha.2
 * @license MIT
 */

declare(strict_types=1);

namespace App\Console\Commands;

use App\Domain\Fields\FieldRegistry;
use App\Domain\Types\ContentType;
use App\Domain\Types\ContentTypeRegistry;
use Illuminate\Console\Command;

final class GenerateFieldsReference extends Command
{
    /** @var string */
    protected $signature = 'teme:docs:fields {--output= : Where to write the reference}';

    /** @var string */
    protected $description = 'Generate the fields reference from the field registry';

    public function handle(FieldRegistry $registry, ContentTypeRegistry $contentTypes): int
    {
        $lines = [
            '# Fields reference',
            '',
            '> Generated by `php artisan teme:docs:fields` from the field registry. **Do not edit** — a hand edit here is a bug in the generator.',
            '',
            'Stored values are keyed by the field\'s **key**, which never changes. The **handle** is what people see and may change.',
            '',
        ];

        // One section per type that has fields, in key order, headed by its
        // singular label.
        $types = $contentTypes->all();
        usort($types, fn (ContentType $a, ContentType $b): int => strcmp($a->key, $b->key));

        foreach ($types as $type) {
            $fields = $registry->forType($type->key);

            if ($fields === []) {
                continue;
            }

            $lines[] = '## '.$type->singular;
            $lines[] = '';
            $lines[] = '| Field | Key | Type | Description | Since |';
            $lines[] = '|---|---|---|---|---|';

            foreach ($fields as $field) {
                $lines[] = sprintf(
                    '| `%s` | `%s` | %s%s | %s | %s |',
                    $field->handle,
                    $field->key,
                    $field->type->name(),
                    $field->required ? ', required' : '',
                    str_replace('|', '\|', $field->description),
                    $field->since,
                );
            }

            $lines[] = '';
        }

        $path = (string) ($this->option('output') ?: base_path('docs/reference/fields.md'));

        if (! is_dir(dirname($path))) {
            mkdir(dirname($path), 0755, true);
        }

        // "\n", not PHP_EOL: the same bytes on every platform (B-037).
        file_put_contents($path, implode("\n", $lines)."\n");

        $this->info("Wrote {$path}");

        return self::SUCCESS;
    }
}
