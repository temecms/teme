<?php

declare(strict_types=1);

namespace App\Console\Commands;

use Illuminate\Console\Command;
use JsonException;
use RuntimeException;

/**
 * `teme:docs:manifest`: writes `docs/reference/plugin-manifest.md` and
 * `theme-manifest.md` from the JSON schemas in teme/contracts.
 */
final class GenerateManifestReference extends Command
{
    /** @var string */
    protected $signature = 'teme:docs:manifest {--output= : Folder to write the reference files into}';

    /** @var string */
    protected $description = 'Generate the plugin and theme manifest references from their JSON schemas';

    public function handle(): int
    {
        $folder = rtrim((string) ($this->option('output') ?: base_path('docs/reference')), '/\\');

        if (! is_dir($folder)) {
            mkdir($folder, 0755, true);
        }

        $this->write(
            $folder.'/plugin-manifest.md',
            'Plugin manifest reference',
            'teme:docs:manifest',
            base_path('packages/teme-contracts/schema/teme-plugin.schema.json'),
            'teme-plugin.json',
        );

        $this->write(
            $folder.'/theme-manifest.md',
            'Theme manifest reference',
            'teme:docs:manifest',
            base_path('packages/teme-contracts/schema/teme-theme.schema.json'),
            'teme-theme.json',
        );

        $this->info("Wrote {$folder}/plugin-manifest.md and {$folder}/theme-manifest.md");

        return self::SUCCESS;
    }

    private function write(string $path, string $title, string $command, string $schemaPath, string $fileName): void
    {
        try {
            $schema = json_decode((string) file_get_contents($schemaPath), true, 512, JSON_THROW_ON_ERROR);
        } catch (JsonException $exception) {
            throw new RuntimeException("Could not read {$schemaPath}: {$exception->getMessage()}", 0, $exception);
        }

        $required = is_array($schema['required'] ?? null) ? $schema['required'] : [];
        $rows = $this->rows($schema, '', $required);

        $lines = [
            '# '.$title,
            '',
            "> Generated by `php artisan {$command}` from `{$fileName}`'s schema. **Do not edit** — a hand edit here is a bug in the generator.",
            '',
            '| Key | Type | Required | Description | Allowed values |',
            '|---|---|---|---|---|',
            ...$rows,
            '',
        ];

        // "\n", not PHP_EOL: the same bytes on every platform (B-037).
        file_put_contents($path, implode("\n", $lines)."\n");
    }

    /**
     * One table row per property path under this schema node.
     *
     * @param  array<string, mixed>  $node
     * @param  list<string|int>  $required
     *
     * @return list<string>
     */
    private function rows(array $node, string $prefix, array $required): array
    {
        $lines = [];
        $properties = is_array($node['properties'] ?? null) ? $node['properties'] : [];

        foreach ($properties as $name => $child) {
            if (! is_array($child)) {
                continue;
            }

            $path = $prefix === '' ? (string) $name : $prefix.'.'.$name;
            $lines[] = $this->row($path, $child, in_array($name, $required, true));
            array_push($lines, ...$this->rows($child, $path, is_array($child['required'] ?? null) ? $child['required'] : []));
        }

        $items = $node['items'] ?? null;

        if (is_array($items)) {
            $itemPrefix = $prefix === '' ? '[]' : $prefix.'[]';
            array_push($lines, ...$this->rows($items, $itemPrefix, is_array($items['required'] ?? null) ? $items['required'] : []));
        }

        $additional = $node['additionalProperties'] ?? null;

        if (is_array($additional)) {
            $extraPrefix = $prefix === '' ? '*' : $prefix.'.*';
            array_push($lines, ...$this->rows($additional, $extraPrefix, is_array($additional['required'] ?? null) ? $additional['required'] : []));
        }

        return $lines;
    }

    /**
     * @param  array<string, mixed>  $node
     */
    private function row(string $path, array $node, bool $required): string
    {
        return sprintf(
            '| `%s` | %s | %s | %s | %s |',
            $path,
            $this->cell($this->typeOf($node)),
            $required ? 'yes' : 'no',
            $this->cell((string) ($node['description'] ?? '')),
            $this->cell($this->allowed($node)),
        );
    }

    /**
     * @param  array<string, mixed>  $node
     */
    private function typeOf(array $node): string
    {
        if (isset($node['const'])) {
            return 'const '.json_encode($node['const'], JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE);
        }

        $type = $node['type'] ?? null;

        if (is_array($type)) {
            return implode('|', array_map(strval(...), $type));
        }

        if (is_string($type)) {
            return $type;
        }

        if (isset($node['enum'])) {
            return 'enum';
        }

        return '';
    }

    /**
     * @param  array<string, mixed>  $node
     */
    private function allowed(array $node): string
    {
        if (isset($node['const'])) {
            return json_encode($node['const'], JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE) ?: '';
        }

        if (isset($node['enum']) && is_array($node['enum'])) {
            return implode(', ', array_map(
                fn (mixed $value): string => (string) json_encode($value, JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE),
                $node['enum'],
            ));
        }

        if (isset($node['pattern']) && is_string($node['pattern'])) {
            return $node['pattern'];
        }

        $items = $node['items'] ?? null;

        if (is_array($items) && isset($items['enum']) && is_array($items['enum'])) {
            return implode(', ', array_map(
                fn (mixed $value): string => (string) json_encode($value, JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE),
                $items['enum'],
            ));
        }

        return '';
    }

    private function cell(string $text): string
    {
        return str_replace('|', '\|', $text);
    }
}
