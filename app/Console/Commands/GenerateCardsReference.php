<?php

declare(strict_types=1);

namespace App\Console\Commands;

use App\Domain\Cards\CardRegistry;
use App\Domain\Cards\CardType;
use Illuminate\Console\Command;

/**
 * `teme:docs:cards`: writes `docs/reference/cards.md` from the card registry,
 * so the reference can never drift from the code.
 */
final class GenerateCardsReference extends Command
{
    /** @var string */
    protected $signature = 'teme:docs:cards {--output= : Where to write the reference}';

    /** @var string */
    protected $description = 'Generate the cards reference from the card registry';

    public function handle(CardRegistry $registry): int
    {
        $lines = [
            '# Cards reference',
            '',
            '> Generated by `php artisan teme:docs:cards` from the card registry. **Do not edit** — a hand edit here is a bug in the generator.',
            '',
            'A card is declared once: its attributes, its HTML, its search text and what it refers to all come from its class. Every card stores `id`, the node\'s stable ID. A document may hold only the cards listed here.',
            '',
        ];

        foreach ($registry->all() as $card) {
            $lines[] = "## `{$card->name()}` — {$card->label()}";
            $lines[] = '';
            $lines[] = $card->description();
            $lines[] = '';
            $lines[] = "Since {$card->since()}. Registered by `{$registry->ownerOf($card->name())}`.";
            $lines[] = '';
            $lines[] = '| Attribute | Rules | Default |';
            $lines[] = '|---|---|---|';

            foreach ($card->attributes() as $name => $attribute) {
                $lines[] = sprintf(
                    '| `%s` | %s | %s |',
                    $name,
                    str_replace('|', '\|', implode(', ', array_map(fn (mixed $rule): string => is_string($rule) ? $rule : get_debug_type($rule), $attribute->rules))),
                    $attribute->default === null ? '—' : '`'.json_encode($attribute->default).'`',
                );
            }

            $lines[] = '';
            $lines[] = 'Refers to: '.$this->refersTo($card);
            $lines[] = '';
        }

        $path = (string) ($this->option('output') ?: base_path('docs/reference/cards.md'));

        if (! is_dir(dirname($path))) {
            mkdir(dirname($path), 0755, true);
        }

        // "\n", not PHP_EOL: the same bytes on every platform (B-037).
        file_put_contents($path, implode("\n", $lines)."\n");

        $this->info("Wrote {$path}");

        return self::SUCCESS;
    }

    /**
     * What the card points at, found by asking the card itself: every
     * attribute is given its own name as a value, and the references that
     * come back say which attributes hold a media or content ID.
     */
    private function refersTo(CardType $card): string
    {
        $probe = [];

        foreach (array_keys($card->attributes()) as $name) {
            $probe[$name] = $name === 'id' ? null : $name;
        }

        // A list attribute, such as a gallery's images, holds its IDs in a list.
        foreach ($card->attributes() as $name => $attribute) {
            if (in_array('array', $attribute->rules, true)) {
                $probe[$name] = [$name];
            }
        }

        $found = [];

        foreach ($card->references($probe) as $reference) {
            $found[] = "{$reference->kind}, by `{$reference->id}`";
        }

        return $found === [] ? 'nothing.' : implode('; ', array_unique($found)).'.';
    }
}
