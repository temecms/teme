<?php

declare(strict_types=1);

namespace App\Console\Commands;

use FilesystemIterator;
use Illuminate\Console\Command;
use RecursiveDirectoryIterator;
use RecursiveIteratorIterator;
use ReflectionClass;
use ReflectionParameter;
use Teme\Contracts\Hooks\Collect;
use Teme\Contracts\Hooks\Gate;
use Teme\Contracts\Hooks\HookContract;
use Teme\Contracts\Hooks\Notification;
use Teme\Contracts\Hooks\Resolve;
use Teme\Contracts\Hooks\Transform;

/**
 * `teme:docs:hooks`: writes `docs/reference/hooks.md` from the hook classes
 * in teme/contracts, so the reference can never drift from the code.
 */
final class GenerateHooksReference extends Command
{
    /** @var list<class-string> */
    private const array VERBS = [
        Notification::class,
        Transform::class,
        Gate::class,
        Resolve::class,
        Collect::class,
    ];

    /** @var string */
    protected $signature = 'teme:docs:hooks
        {--output= : Where to write the reference}
        {--source= : Directory of PHP files to scan instead of the contracts package}
        {--namespace= : PSR-4 namespace for --source (required with --source)}';

    /** @var string */
    protected $description = 'Generate the hooks reference from the contracts package';

    public function handle(): int
    {
        $source = (string) ($this->option('source') ?: base_path('packages/teme-contracts/src'));
        $namespace = (string) ($this->option('namespace') ?: 'Teme\\Contracts');

        if ($this->option('source') !== null && $this->option('namespace') === null) {
            $this->error('Pass --namespace with --source.');

            return self::FAILURE;
        }

        $hooks = $this->discover($source, $namespace);
        $missing = [];

        foreach ($hooks as $class) {
            if ($this->since((new ReflectionClass($class))->getDocComment()) === null) {
                $missing[] = $class;
            }
        }

        if ($missing !== []) {
            foreach ($missing as $class) {
                $this->error("{$class} has no @since.");
            }

            return self::FAILURE;
        }

        $lines = [
            '# Hooks reference',
            '',
            '> Generated by `php artisan teme:docs:hooks` from the hook classes in `teme/contracts`. **Do not edit** — a hand edit here is a bug in the generator.',
            '',
        ];

        foreach ($hooks as $class) {
            array_push($lines, ...$this->section($class));
        }

        $path = (string) ($this->option('output') ?: base_path('docs/reference/hooks.md'));

        if (! is_dir(dirname($path))) {
            mkdir(dirname($path), 0755, true);
        }

        // "\n", not PHP_EOL: the same bytes on every platform (B-037).
        file_put_contents($path, implode("\n", $lines)."\n");

        $this->info("Wrote {$path}");

        return self::SUCCESS;
    }

    /**
     * Hook classes under $source that implement a verb, sorted by namespace then name.
     *
     * @return list<class-string>
     */
    private function discover(string $source, string $namespace): array
    {
        $found = [];
        $prefix = rtrim($namespace, '\\').'\\';

        foreach (new RecursiveIteratorIterator(new RecursiveDirectoryIterator($source, FilesystemIterator::SKIP_DOTS)) as $file) {
            if ($file->getExtension() !== 'php') {
                continue;
            }

            $relative = substr($file->getPathname(), strlen(rtrim($source, '/\\')) + 1, -4);
            $class = $prefix.str_replace(['/', '\\'], '\\', $relative);

            if (! class_exists($class)) {
                require_once $file->getPathname();
            }

            if (! class_exists($class)) {
                continue;
            }

            $reflection = new ReflectionClass($class);

            if ($reflection->isInterface() || $reflection->isTrait() || $reflection->isAbstract()) {
                continue;
            }

            foreach (self::VERBS as $verb) {
                if ($reflection->implementsInterface($verb)) {
                    $found[] = $class;

                    break;
                }
            }
        }

        usort($found, function (string $a, string $b): int {
            $byNamespace = strcmp($this->namespaceOf($a), $this->namespaceOf($b));

            return $byNamespace !== 0 ? $byNamespace : strcmp(class_basename($a), class_basename($b));
        });

        return $found;
    }

    /**
     * One markdown section for a hook class.
     *
     * @param  class-string  $class
     *
     * @return list<string>
     */
    private function section(string $class): array
    {
        $reflection = new ReflectionClass($class);
        $attributes = $reflection->getAttributes(HookContract::class);
        $contract = $attributes === [] ? null : $attributes[0]->newInstance();
        $verb = $this->verbName($reflection);
        $capability = $contract?->capability;
        $summary = $this->firstParagraph($reflection->getDocComment());
        $since = $this->since($reflection->getDocComment()) ?? '';

        $lines = [
            '## '.class_basename($class),
            '',
            $summary,
            '',
            '- **Class:** `'.$class.'`',
            '- **Verb:** '.$verb,
            '- **Capability:** '.($capability === null ? 'none' : '`'.$capability.'`'),
            '- **Since:** '.$since,
            '',
        ];

        $constructor = $reflection->getConstructor();

        if ($constructor !== null && $constructor->getParameters() !== []) {
            $lines[] = '| Parameter | Description |';
            $lines[] = '|---|---|';

            foreach ($constructor->getParameters() as $parameter) {
                $lines[] = sprintf(
                    '| `%s` | %s |',
                    $parameter->getName(),
                    str_replace('|', '\|', $this->paramText($constructor->getDocComment(), $parameter)),
                );
            }

            $lines[] = '';
        }

        return $lines;
    }

    /**
     * @param  ReflectionClass<object>  $reflection
     */
    private function verbName(ReflectionClass $reflection): string
    {
        foreach (self::VERBS as $verb) {
            if ($reflection->implementsInterface($verb)) {
                return class_basename($verb);
            }
        }

        return '';
    }

    private function namespaceOf(string $class): string
    {
        $pos = strrpos($class, '\\');

        return $pos === false ? '' : substr($class, 0, $pos);
    }

    /**
     * The class docblock's first paragraph of prose, before any @tag.
     */
    private function firstParagraph(string|false $docComment): string
    {
        if ($docComment === false) {
            return '';
        }

        $lines = [];

        foreach (preg_split('/\R/', $docComment) ?: [] as $line) {
            $line = trim((string) preg_replace('#^\s*(/\*\*|\*/|\*)#', '', trim($line)));
            $line = trim((string) preg_replace('#\*/$#', '', $line));

            if (str_starts_with($line, '@')) {
                break;
            }

            if ($line === '') {
                if ($lines !== []) {
                    break;
                }

                continue;
            }

            $lines[] = $line;
        }

        return implode(' ', $lines);
    }

    /**
     * The @since value on the class docblock, or null when missing.
     */
    private function since(string|false $docComment): ?string
    {
        if ($docComment === false) {
            return null;
        }

        return preg_match('/@since\s+(\S+)/', $docComment, $found) === 1 ? $found[1] : null;
    }

    /**
     * The @param description for a constructor parameter.
     */
    private function paramText(string|false $docComment, ReflectionParameter $parameter): string
    {
        if ($docComment === false) {
            return '';
        }

        $name = preg_quote($parameter->getName(), '/');

        if (preg_match('/@param\s+\S+\s+\$'.$name.'\s+(.+)$/m', $docComment, $found) === 1) {
            return trim($found[1]);
        }

        return '';
    }
}
