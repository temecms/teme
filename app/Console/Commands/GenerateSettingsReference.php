<?php

/**
 * `teme:docs:settings`: writes `docs/reference/settings.md` from the settings
 * registry. The reference is generated, never edited by hand.
 *
 * @package Teme
 * @since   0.7.0-alpha.2
 * @license MIT
 */

declare(strict_types=1);

namespace App\Console\Commands;

use App\Domain\Settings\SettingsRegistry;
use Illuminate\Console\Command;
use Teme\Contracts\Settings\SettingType;

final class GenerateSettingsReference extends Command
{
    /** @var string */
    protected $signature = 'teme:docs:settings {--output= : Where to write the reference}';

    /** @var string */
    protected $description = 'Generate the settings reference from the settings registry';

    public function handle(SettingsRegistry $registry): int
    {
        $lines = [
            '# Settings reference',
            '',
            '> Generated by `php artisan teme:docs:settings` from the settings registry. **Do not edit** — a hand edit here is a bug in the generator.',
            '',
        ];

        foreach ($registry->all() as $group) {
            $lines[] = "## {$group->label}";
            $lines[] = '';
            $lines[] = $group->description;
            $lines[] = '';
            $lines[] = "Changing these requires `{$group->ability}`. Since {$group->since}.";
            $lines[] = '';
            $lines[] = '| Setting | Type | Default | Description | Since |';
            $lines[] = '|---|---|---|---|---|';

            foreach ($group->settings as $setting) {
                $default = $setting->type === SettingType::Secret
                    ? '—'
                    : '`'.json_encode($setting->default, JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE).'`';

                $lines[] = sprintf(
                    '| `%s.%s` | %s%s | %s | %s | %s |',
                    $group->key,
                    $setting->key,
                    $setting->type->value,
                    $setting->required ? ', required' : '',
                    $default,
                    str_replace('|', '\|', $setting->description),
                    $setting->since,
                );
            }

            $lines[] = '';
        }

        $path = (string) ($this->option('output') ?: base_path('docs/reference/settings.md'));

        if (! is_dir(dirname($path))) {
            mkdir(dirname($path), 0755, true);
        }

        // "\n", not PHP_EOL: the same bytes on every platform, so a regenerate-
        // and-diff check never reports line endings.
        file_put_contents($path, implode("\n", $lines)."\n");

        $this->info("Wrote {$path}");

        return self::SUCCESS;
    }
}
