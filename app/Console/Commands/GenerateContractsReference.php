<?php

declare(strict_types=1);

namespace App\Console\Commands;

use App\Domain\Plugins\Seams\PluginServices;
use FilesystemIterator;
use Illuminate\Console\Command;
use RecursiveDirectoryIterator;
use RecursiveIteratorIterator;
use ReflectionClass;
use ReflectionClassConstant;
use ReflectionIntersectionType;
use ReflectionMethod;
use ReflectionNamedType;
use ReflectionParameter;
use ReflectionType;
use ReflectionUnionType;
use Teme\Contracts\Ai\SiteAi;
use Teme\Contracts\Hooks\Collect;
use Teme\Contracts\Hooks\Gate;
use Teme\Contracts\Hooks\HookSender;
use Teme\Contracts\Hooks\Notification;
use Teme\Contracts\Hooks\Resolve;
use Teme\Contracts\Hooks\Transform;
use Teme\Contracts\Plugins\Capability;
use Teme\Contracts\Settings\PluginSettingsWriter;

/**
 * `teme:docs:contracts`: writes `docs/reference/contracts.md`, every
 * interface, class and enum in teme/contracts with its methods, constants
 * and `@since`, and what a plugin's constructor may ask for, computed from
 * the doors Teme really hands out, so the page can't drift from the code.
 */
final class GenerateContractsReference extends Command
{
    /** @var list<class-string> */
    private const array VERBS = [Notification::class, Transform::class, Gate::class, Resolve::class, Collect::class];

    /** The hosts the probe plugin asks for, so a door that needs some is offered. */
    private const array PROBE_HOSTS = ['example.com'];

    /**
     * The contracts given for what the manifest declares rather than for a
     * capability, with the manifest key that gives each; the probe plugin
     * has no manifest, so these are taken as stated.
     *
     * @var array<class-string, string>
     */
    private const array BY_DECLARATION = [PluginSettingsWriter::class => 'contributes.settings', HookSender::class => 'contributes.hooks'];

    /**
     * The contracts given only when a grant and a declaration meet, with
     * each's grant and manifest key; taken as stated, as above.
     *
     * @var array<class-string, array{0: string, 1: string}>
     */
    private const array BY_GRANT_AND_DECLARATION = [SiteAi::class => [Capability::Ai->value, 'contributes.aiTasks']];

    /** @var string */
    protected $signature = 'teme:docs:contracts
        {--output= : Where to write the reference}
        {--source= : Directory of PHP files to scan instead of the contracts package}
        {--namespace= : PSR-4 namespace for --source (required with --source)}';

    /** @var string */
    protected $description = 'Generate the contracts reference, with what a plugin\'s constructor may ask for';

    public function handle(PluginServices $services): int
    {
        if ($this->option('source') !== null && $this->option('namespace') === null) {
            $this->error('Pass --namespace with --source.');

            return self::FAILURE;
        }

        $source = (string) ($this->option('source') ?: base_path('packages/teme-contracts/src'));
        $namespace = rtrim((string) ($this->option('namespace') ?: 'Teme\\Contracts'), '\\');
        $types = $this->discover($source, $namespace);
        $missing = $this->withoutSince($types);

        if ($missing !== []) {
            foreach ($missing as $name) {
                $this->error("{$name} has no @since.");
            }

            return self::FAILURE;
        }

        [$offered, $problems] = $this->offered($services);

        if ($problems !== []) {
            foreach ($problems as $problem) {
                $this->error($problem);
            }

            return self::FAILURE;
        }

        $lines = [
            '# Contracts reference',
            '',
            '> Generated by `php artisan teme:docs:contracts` from `teme/contracts`. **Do not edit** — a hand edit here is a bug in the generator.',
            '',
            'This checkout offers contracts up to **'.$this->highest($types).'**.',
            '',
            '## What a plugin\'s constructor may ask for',
            '',
            'Teme builds a plugin\'s class with only these, each when the plugin was granted, or its manifest declares, what the second column names. A constructor that asks for anything else is refused when the plugin is enabled.',
            '',
            '| Contract | Given when | Since |',
            '|---|---|---|',
        ];

        foreach ($offered as $class => $when) {
            $lines[] = sprintf('| `%s` | %s | %s |', $class, match (true) {
                $when === null => 'always',
                str_starts_with($when, 'declares ') => 'its manifest declares `'.substr($when, 9).'`',
                str_starts_with($when, 'granted ') => vsprintf('granted `%s` and its manifest declares `%s`', explode(' declares ', substr($when, 8))),
                default => 'granted `'.$when.'`',
            }, $this->since($class));
        }

        $lines[] = '';

        foreach ($this->byNamespace($types, $namespace) as $group => $members) {
            array_push($lines, '## '.$group, '');

            foreach ($members as $class) {
                array_push($lines, ...$this->section($class));
            }
        }

        $path = (string) ($this->option('output') ?: base_path('docs/reference/contracts.md'));

        if (! is_dir(dirname($path))) {
            mkdir(dirname($path), 0755, true);
        }

        // "\n", not PHP_EOL: the same bytes on every platform.
        file_put_contents($path, implode("\n", $lines)."\n");

        $this->info("Wrote {$path}");

        return self::SUCCESS;
    }

    /**
     * Every interface, class, enum and trait under $source, one per file, sorted by name.
     *
     * @return list<class-string>
     */
    private function discover(string $source, string $namespace): array
    {
        $found = [];

        foreach (new RecursiveIteratorIterator(new RecursiveDirectoryIterator($source, FilesystemIterator::SKIP_DOTS)) as $file) {
            if ($file->getExtension() !== 'php') {
                continue;
            }

            $relative = substr($file->getPathname(), strlen(rtrim($source, '/\\')) + 1, -4);
            $class = $namespace.'\\'.str_replace(['/', '\\'], '\\', $relative);

            if (! $this->exists($class)) {
                require_once $file->getPathname();
            }

            if ($this->exists($class)) {
                $found[] = $class;
            }
        }

        sort($found);

        /** @var list<class-string> $found */
        return $found;
    }

    private function exists(string $class): bool
    {
        return class_exists($class) || interface_exists($class) || enum_exists($class) || trait_exists($class);
    }

    /**
     * Each public type, method, constant and enum case these types declare
     * without an `@since` of its own, by name.
     *
     * @param  list<class-string>  $types
     *
     * @return list<string>
     */
    private function withoutSince(array $types): array
    {
        $missing = [];

        foreach ($types as $class) {
            $reflection = new ReflectionClass($class);

            if ($this->sinceIn($reflection->getDocComment()) === null) {
                $missing[] = $class;
            }

            foreach ($this->methods($reflection) as $method) {
                if ($this->sinceIn($method->getDocComment()) === null) {
                    $missing[] = $class.'::'.$method->getName().'()';
                }
            }

            foreach ($this->constants($reflection) as $constant) {
                if ($this->sinceIn($constant->getDocComment()) === null) {
                    $missing[] = $class.'::'.$constant->getName();
                }
            }
        }

        return $missing;
    }

    /**
     * Each contract a plugin's constructor may be given, with the capability
     * that gives it, or null when every plugin is given it: asked of the
     * bound doors for a plugin granted nothing, then for one granted each
     * capability alone. Then every problem: a contract listed as offered
     * that no grant gives, or one given that isn't listed.
     *
     * @return array{0: array<class-string, string|null>, 1: list<string>}
     */
    private function offered(PluginServices $services): array
    {
        $always = array_keys($services->for('teme-docs/probe', 'teme-docs-probe', [], self::PROBE_HOSTS));
        $offered = array_fill_keys($always, null);

        foreach (Capability::cases() as $capability) {
            foreach (array_keys($services->for('teme-docs/probe', 'teme-docs-probe', [$capability->value], self::PROBE_HOSTS)) as $class) {
                if (! array_key_exists($class, $offered)) {
                    $offered[$class] = $capability->value;
                }
            }
        }

        foreach (self::BY_DECLARATION as $class => $key) {
            if (! array_key_exists($class, $offered)) {
                $offered[$class] = 'declares '.$key;
            }
        }

        foreach (self::BY_GRANT_AND_DECLARATION as $class => [$grant, $key]) {
            if (! array_key_exists($class, $offered)) {
                $offered[$class] = 'granted '.$grant.' declares '.$key;
            }
        }

        $problems = [];

        foreach (PluginServices::OFFERED as $class) {
            if (! array_key_exists($class, $offered)) {
                $problems[] = "{$class} is listed as offered, but no grant gives it.";
            }
        }

        foreach (array_keys($offered) as $class) {
            if (! in_array($class, PluginServices::OFFERED, true)) {
                $problems[] = "{$class} is given to plugins, but PluginServices::OFFERED doesn't list it.";
            }
        }

        $ordered = [];

        foreach (PluginServices::OFFERED as $class) {
            if (array_key_exists($class, $offered)) {
                $ordered[$class] = $offered[$class];
            }
        }

        return [$ordered, $problems];
    }

    /**
     * The highest `@since` among these types and their members.
     *
     * @param  list<class-string>  $types
     */
    private function highest(array $types): string
    {
        $highest = '0.0.0';

        foreach ($types as $class) {
            $reflection = new ReflectionClass($class);
            $docs = [$reflection->getDocComment()];

            foreach ($this->methods($reflection) as $method) {
                $docs[] = $method->getDocComment();
            }

            foreach ($this->constants($reflection) as $constant) {
                $docs[] = $constant->getDocComment();
            }

            foreach ($docs as $doc) {
                $since = $this->sinceIn($doc);

                if ($since !== null && version_compare($since, $highest, '>')) {
                    $highest = $since;
                }
            }
        }

        return $highest;
    }

    /**
     * The types grouped by the namespace under the root, in name order.
     *
     * @param  list<class-string>  $types
     *
     * @return array<string, list<class-string>>
     */
    private function byNamespace(array $types, string $root): array
    {
        $groups = [];

        foreach ($types as $class) {
            $namespace = substr($class, 0, (int) strrpos($class, '\\'));
            $groups[$namespace === $root ? $root : $namespace][] = $class;
        }

        ksort($groups);

        return $groups;
    }

    /**
     * One type's section: its kind, what it is for, its `@since`, then its
     * public methods and constants, or for a hook a link to its section in
     * the hooks reference.
     *
     * @param  class-string  $class
     *
     * @return list<string>
     */
    private function section(string $class): array
    {
        $reflection = new ReflectionClass($class);
        $lines = [
            '### '.$reflection->getShortName(),
            '',
            '`'.$class.'`, '.$this->kind($reflection).'. Since '.$this->since($class).'.',
            '',
        ];

        $summary = $this->firstParagraph($reflection->getDocComment());

        if ($summary !== '') {
            array_push($lines, $summary, '');
        }

        if ($this->isHook($reflection)) {
            array_push($lines, 'A hook: its parameters are in the [hooks reference](hooks.md#'.strtolower($reflection->getShortName()).').', '');

            return $lines;
        }

        $members = [];

        foreach ($this->constants($reflection) as $constant) {
            $label = $reflection->isEnum() && $constant->isEnumCase() ? 'case `'.$constant->getName().'`' : '`'.$constant->getName().'`';
            $members[] = '- '.$label.$this->sentence($constant->getDocComment()).' Since '.$this->sinceIn($constant->getDocComment()).'.';
        }

        foreach ($this->methods($reflection) as $method) {
            $members[] = '- `'.$this->signature($method).'`'.$this->sentence($method->getDocComment()).' Since '.$this->sinceIn($method->getDocComment()).'.';
        }

        if ($members !== []) {
            array_push($lines, ...$members);
            $lines[] = '';
        }

        return $lines;
    }

    /**
     * @param  ReflectionClass<object>  $reflection
     */
    private function kind(ReflectionClass $reflection): string
    {
        return match (true) {
            $reflection->isInterface() => 'interface',
            $reflection->isEnum() => 'enum',
            $reflection->isTrait() => 'trait',
            $reflection->isAbstract() => 'abstract class',
            default => 'class',
        };
    }

    /**
     * @param  ReflectionClass<object>  $reflection
     */
    private function isHook(ReflectionClass $reflection): bool
    {
        if ($reflection->isInterface() || $reflection->isTrait() || $reflection->isAbstract()) {
            return false;
        }

        foreach (self::VERBS as $verb) {
            if ($reflection->implementsInterface($verb)) {
                return true;
            }
        }

        return false;
    }

    /**
     * The public methods this type declares itself, never PHP's own on an enum.
     *
     * @param  ReflectionClass<object>  $reflection
     *
     * @return list<ReflectionMethod>
     */
    private function methods(ReflectionClass $reflection): array
    {
        $methods = [];

        foreach ($reflection->getMethods(ReflectionMethod::IS_PUBLIC) as $method) {
            if ($method->getDeclaringClass()->getName() !== $reflection->getName() || $method->getFileName() !== $reflection->getFileName()) {
                continue;
            }

            if ($reflection->isEnum() && in_array($method->getName(), ['cases', 'from', 'tryFrom'], true)) {
                continue;
            }

            $methods[] = $method;
        }

        return $methods;
    }

    /**
     * The public constants and enum cases this type declares itself.
     *
     * @param  ReflectionClass<object>  $reflection
     *
     * @return list<ReflectionClassConstant>
     */
    private function constants(ReflectionClass $reflection): array
    {
        $constants = [];

        foreach ($reflection->getReflectionConstants(ReflectionClassConstant::IS_PUBLIC) as $constant) {
            if ($constant->getDeclaringClass()->getName() === $reflection->getName()) {
                $constants[] = $constant;
            }
        }

        return $constants;
    }

    /**
     * `name(parameters): return`, as the method is declared.
     */
    private function signature(ReflectionMethod $method): string
    {
        $parameters = array_map($this->parameter(...), $method->getParameters());
        $return = $method->getReturnType();

        return $method->getName().'('.implode(', ', $parameters).')'.($return === null ? '' : ': '.$this->type($return));
    }

    private function parameter(ReflectionParameter $parameter): string
    {
        $type = $parameter->getType();
        $text = ($type === null ? '' : $this->type($type).' ').($parameter->isVariadic() ? '...' : '').'$'.$parameter->getName();

        if (! $parameter->isDefaultValueAvailable()) {
            return $text;
        }

        if ($parameter->isDefaultValueConstant()) {
            $constant = (string) $parameter->getDefaultValueConstantName();

            return $text.' = '.(str_contains($constant, '\\') ? substr($constant, (int) strrpos($constant, '\\') + 1) : $constant);
        }

        return $text.' = '.$this->value($parameter->getDefaultValue());
    }

    private function value(mixed $value): string
    {
        return match (true) {
            $value === null => 'null',
            $value === [] => '[]',
            is_bool($value) => $value ? 'true' : 'false',
            is_string($value) => "'".$value."'",
            is_int($value), is_float($value) => (string) $value,
            is_object($value) => 'new '.substr($value::class, (int) strrpos($value::class, '\\') + 1).'()',
            default => '…',
        };
    }

    /**
     * A type as written, with names short where they are Teme's contracts or PHP's own.
     */
    private function type(ReflectionType $type): string
    {
        if ($type instanceof ReflectionUnionType) {
            return implode('|', array_map($this->type(...), $type->getTypes()));
        }

        if ($type instanceof ReflectionIntersectionType) {
            return implode('&', array_map($this->type(...), $type->getTypes()));
        }

        if (! $type instanceof ReflectionNamedType) {
            return (string) $type;
        }

        $name = $type->getName();
        $short = $type->isBuiltin() ? $name : substr($name, (int) strrpos($name, '\\') + (str_contains($name, '\\') ? 1 : 0));
        $nullable = $type->allowsNull() && ! in_array($name, ['null', 'mixed'], true);

        return ($nullable ? '?' : '').$short;
    }

    /**
     * The type's own `@since`, by class name.
     */
    private function since(string $class): string
    {
        return $this->sinceIn((new ReflectionClass($class))->getDocComment()) ?? '';
    }

    /**
     * The `@since` value in this docblock, or null when it has none.
     */
    private function sinceIn(string|false $docComment): ?string
    {
        if ($docComment === false) {
            return null;
        }

        return preg_match('/@since\s+(\S+?)(?:\s|\*|$)/', $docComment, $found) === 1 ? $found[1] : null;
    }

    /**
     * The docblock's first sentence, after a dash, or a full stop when it has no prose.
     */
    private function sentence(string|false $docComment): string
    {
        $paragraph = $this->firstParagraph($docComment);

        if ($paragraph === '') {
            return '.';
        }

        $sentence = preg_match('/^(.+?[.!?])(?:\s|$)/u', $paragraph, $found) === 1 ? $found[1] : $paragraph;

        return ' — '.$sentence;
    }

    /**
     * The docblock's first paragraph of prose, before any @tag.
     */
    private function firstParagraph(string|false $docComment): string
    {
        if ($docComment === false) {
            return '';
        }

        $lines = [];

        foreach (preg_split('/\R/', $docComment) ?: [] as $line) {
            $line = trim((string) preg_replace('#^\s*(/\*\*|\*/|\*)#', '', trim($line)));
            $line = trim((string) preg_replace('#\*/$#', '', $line));

            if (str_starts_with($line, '@')) {
                break;
            }

            // A one-line docblock's prose stops at its first tag.
            $line = trim((string) preg_replace('/\s@\w.*$/', '', $line));

            if ($line === '') {
                if ($lines !== []) {
                    break;
                }

                continue;
            }

            $lines[] = $line;
        }

        return implode(' ', $lines);
    }
}
