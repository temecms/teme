<?php

declare(strict_types=1);

namespace App\Console\Commands;

use App\Domain\Themes\Reference\ThemeReference;
use App\Domain\Themes\Reference\ViewDataCatalogue;
use App\Domain\Themes\Reference\ViewDataPin;
use Illuminate\Console\Command;

/**
 * `teme:docs:theme`: writes `docs/reference/theme.md` and the pin of
 * everything a template can read, `docs/reference/theme-view-data.json`, from
 * the code and the manifest's schema (I-3346).
 */
final class GenerateThemeReference extends Command
{
    /** @var string */
    protected $signature = 'teme:docs:theme {--output= : The folder to write the reference and its pin into}';

    /** @var string */
    protected $description = 'Generate the theme reference and the pin of the values a template can read';

    public function handle(ViewDataCatalogue $catalogue, ThemeReference $reference): int
    {
        $schema = json_decode((string) file_get_contents(base_path('packages/teme-contracts/schema/teme-theme.schema.json')), true, 512, JSON_THROW_ON_ERROR);

        // The previous pin is always the committed one, whatever the output folder, so a test can generate elsewhere and compare.
        $pinPath = base_path('docs/reference/theme-view-data.json');
        $previous = is_file($pinPath) ? json_decode((string) file_get_contents($pinPath), true, 512, JSON_THROW_ON_ERROR)['entries'] ?? [] : [];

        $types = array_map(fn (array $entry): string => $entry['type'], $catalogue->entries());
        $pin = [
            'about' => 'Generated by php artisan teme:docs:theme. A value marked gone or with was must be named in CHANGELOG.md under ### Theme view data.',
            'entries' => ViewDataPin::updated($previous, $types),
        ];

        $folder = rtrim((string) ($this->option('output') ?: base_path('docs/reference')), '/\\');

        if (! is_dir($folder)) {
            mkdir($folder, 0755, true);
        }

        // "\n", not PHP_EOL: the same bytes on every platform (B-037).
        file_put_contents($folder.'/theme.md', $reference->markdown($catalogue, $schema));
        file_put_contents($folder.'/theme-view-data.json', json_encode($pin, JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE | JSON_THROW_ON_ERROR)."\n");

        $this->info("Wrote {$folder}/theme.md and {$folder}/theme-view-data.json");

        return self::SUCCESS;
    }
}
