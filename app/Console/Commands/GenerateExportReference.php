<?php

/**
 * `teme:docs:export`: writes `docs/reference/export.md` from the export's
 * kinds, its manifest and what it leaves out (I-365). The reference is
 * generated, never edited by hand.
 *
 * @package Teme
 * @since   0.7.0-alpha.2
 * @license MIT
 */

declare(strict_types=1);

namespace App\Console\Commands;

use App\Domain\Export\ExportKind;
use App\Domain\Export\ExportKinds;
use App\Domain\Export\ExportManifest;
use App\Domain\Export\LeftOut;
use Illuminate\Console\Command;

final class GenerateExportReference extends Command
{
    /** @var list<string> */
    private const array INTRODUCTION = [
        '**Every line** is one JSON object on one line, ending in `\n`, UTF-8. Its first two keys:',
        '- `kind`: the file\'s kind, as named below.',
        '- `version`: the kind\'s version: 1 for every kind in this release.',
        '',
        '**Times** are UTC, `2026-10-20T14:03:07.123456Z`. **IDs** are as Teme stores them: items, terms, comments, menus, menu items, redirects and people\'s bylines as lowercase ULIDs; media as uppercase ULIDs; people as whole numbers. **Documents** (`document`, `body`) are Tiptap JSON as the editor stores it; an internal link\'s `href` is `teme:content/<item ID>`, and an image names its media by `mediaId`. **Fields** are each item\'s typed fields as stored, media and people by ID.',
        '',
        '**The files are written in this order**, each before the files that refer to it, so an importer can read them in turn:',
    ];

    /** @var string */
    protected $signature = 'teme:docs:export {--output= : Where to write the reference}';

    /** @var string */
    protected $description = 'Generate the export format reference from the export’s kinds';

    public function handle(ExportKinds $kinds): int
    {
        $lines = [
            '# Export format reference',
            '',
            '> Generated by `php artisan teme:docs:export` from the export’s kinds. **Do not edit** — a hand edit here is a bug in the generator.',
            '',
            ...self::INTRODUCTION,
            implode(', ', array_map(fn (ExportKind $kind): string => "`{$kind->name()}`", $kinds->all())).'.',
            '',
        ];

        foreach ($kinds->all() as $kind) {
            $lines[] = "## `{$kind->name()}.ndjson`";
            $lines[] = '';
            $lines[] = "Kind `{$kind->name()}`, version {$kind->version()}. {$kind->description()}";
            $lines[] = '';
            array_push($lines, ...self::fieldTable($kind->fields()));
        }

        $lines[] = '## `manifest.json`';
        $lines[] = '';
        $lines[] = 'Written last; an export folder without one is incomplete.';
        $lines[] = '';
        array_push($lines, ...self::fieldTable(ExportManifest::FIELDS));

        $lines[] = '## What the export leaves out';
        $lines[] = '';
        $lines[] = '| What | Why |';
        $lines[] = '|---|---|';

        foreach (LeftOut::ALL as $row) {
            $lines[] = '| '.self::cell($row['what']).' | '.self::cell($row['why']).' |';
        }

        $lines[] = '';

        $path = (string) ($this->option('output') ?: base_path('docs/reference/export.md'));

        if (! is_dir(dirname($path))) {
            mkdir(dirname($path), 0755, true);
        }

        // "\n", not PHP_EOL: the same bytes on every platform, so a regenerate-
        // and-diff check never reports line endings.
        file_put_contents($path, implode("\n", $lines)."\n");

        $this->info("Wrote {$path}");

        return self::SUCCESS;
    }

    /**
     * A key-and-words table, a blank line after it.
     *
     * @param  array<string, string>  $fields
     *
     * @return list<string>
     */
    private static function fieldTable(array $fields): array
    {
        $lines = ['| Key | What it holds |', '|---|---|'];

        foreach ($fields as $key => $text) {
            $lines[] = "| `{$key}` | ".self::cell($text).' |';
        }

        $lines[] = '';

        return $lines;
    }

    private static function cell(string $text): string
    {
        return str_replace('|', '\|', $text);
    }
}
