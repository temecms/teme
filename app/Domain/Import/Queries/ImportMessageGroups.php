    /**
     * Returns the plain group name and sentence for a message code. The
     * sentence is null when the report should keep the first message's words.
     *
     * @return array{group: string, sentence: string|null}
     */
    public static function for(string $code): array
    {
        $row = self::GROUPS[$code] ?? null;

        if ($row !== null) {
            return [
                'group' => __($row['group']),
                'sentence' => $row['sentence'] === null ? null : __($row['sentence']),
            ];
        }

        return [
            'group' => __('Other notes'),
            'sentence' => null,
        ];
    }

    /**
     * Whether this code has a dedicated group entry (used by the map test).
     */
    public static function maps(string $code): bool
    {
        return array_key_exists($code, self::GROUPS);
    }
