<?php

/**
 * Writes docs/reference/theme.md: the manifest, the kinds of page, what every
 * template gets, the page's values, the field values and the components, from the schema and
 * the catalogue, the same on every machine (I-3346).
 *
 * @package Teme
 * @since   0.7.0-alpha.2
 * @license MIT
 */

declare(strict_types=1);

namespace App\Domain\Themes\Reference;

use App\Domain\Site\FieldViews;
use App\Domain\Themes\TemplateResolver;
use App\Domain\Themes\ViewIntent;

final class ThemeReference
{
    public function __construct(private readonly TemplateResolver $resolver) {}

    /**
     * The reference as markdown, with "\n" line endings and one at the end.
     *
     * @param  array<string, mixed>  $schema  the manifest's JSON Schema, decoded
     */
    public function markdown(ViewDataCatalogue $catalogue, array $schema): string
    {
        $lines = [
            '# Theme reference',
            '',
            '> Generated by `php artisan teme:docs:theme` from the code. **Do not edit** — a hand edit here is a bug in the generator.',
            '',
            'Every rename, change of type or removal is named in `CHANGELOG.md` under *Theme view data*.',
            '',
            ...$this->manifest($schema),
            ...$this->kinds($catalogue),
            ...$this->variables($catalogue),
            ...$this->values($catalogue),
            ...$this->fieldValues(),
            ...$this->components($catalogue),
        ];

        return rtrim(implode("\n", $lines))."\n";
    }

    /**
     * @param  array<string, mixed>  $schema
     * @return list<string>
     */
    private function manifest(array $schema): array
    {
        $lines = [
            '## The manifest',
            '',
            '`teme-theme.json`, version 1. Its JSON Schema is `vendor/teme/contracts/schema/teme-theme.schema.json`: point the manifest’s `$schema` at it for an editor’s help.',
            '',
            '| Key | Type | Required | Description |',
            '|---|---|---|---|',
        ];

        foreach ($schema['properties'] as $key => $property) {
            $type = implode('|', (array) ($property['type'] ?? []));
            $lines[] = sprintf(
                '| `%s` | %s | %s | %s |',
                $key,
                $this->cell($type),
                in_array($key, $schema['required'], true) ? 'yes' : 'no',
                $this->cell((string) ($property['description'] ?? '')),
            );
        }

        return [...$lines, ''];
    }

    /** @return list<string> */
    private function kinds(ViewDataCatalogue $catalogue): array
    {
        $samples = [
            'single' => new ViewIntent('single', type: 'post', template: 'full-width'),
            'archive' => new ViewIntent('archive', type: 'post'),
            'taxonomy' => new ViewIntent('taxonomy', taxonomy: 'category', term: 'news'),
            'error' => new ViewIntent('error', code: 404),
        ];
        $lines = [
            '## Kinds of page',
            '',
            '| Kind | `$page` | Templates tried, in order |',
            '|---|---|---|',
        ];

        foreach (ViewIntent::KINDS as $kind) {
            $candidates = $this->resolver->candidates($samples[$kind] ?? new ViewIntent($kind));
            $names = array_map(fn (string $name): string => '`'.substr($name, strlen('templates.')).'`', $candidates);
            $lines[] = sprintf('| `%s` | `%s` | %s |', $kind, $catalogue->short(ViewDataCatalogue::PAGE_MODELS[$kind]), implode(', ', $names));
        }

        return [
            ...$lines,
            '',
            '`index` is the floor every kind but `error` falls to. An `error` falls to core’s own error page; `comments`, `respond` and `protected` fall to core’s own page. A theme names no list of the types or taxonomies it draws: a file named for one draws it, and `single` and `archive` draw the rest.',
            '',
        ];
    }

    /** @return list<string> */
    private function variables(ViewDataCatalogue $catalogue): array
    {
        $lines = [
            '## What every template gets',
            '',
            '| Name | Type | Description |',
            '|---|---|---|',
        ];

        foreach ($catalogue->variables() as $name => $variable) {
            $lines[] = sprintf('| `%s` | `%s` | %s |', $name, $this->code($variable['type']), $this->cell($variable['description']));
        }

        return [
            ...$lines,
            '',
            'Laravel’s own `$errors`, `$attributes` and `$slot` are Blade’s, not Teme’s, and may change with Laravel.',
            '',
            // Room left for a site in several languages (I-3360).
            'Core may add `language`, `direction` and `alternates` to a page’s data; a theme’s composer must not return them.',
            '',
            'A theme never writes `dir` or `lang`: the page’s shell does. Use logical CSS properties (start and end, not left and right).',
            '',
        ];
    }

    /** @return list<string> */
    private function values(ViewDataCatalogue $catalogue): array
    {
        $lines = ['## The page’s values', ''];

        foreach ($catalogue->classes() as $class) {
            $lines[] = '### '.$catalogue->short($class);
            $lines[] = '';

            $description = $catalogue->classDescription($class);

            if ($description !== '') {
                $lines[] = $this->cell($description);
                $lines[] = '';
            }

            $lines[] = '| Name | Type | Description |';
            $lines[] = '|---|---|---|';

            foreach ($catalogue->members($class) as $member) {
                $lines[] = sprintf('| `%s` | `%s` | %s |', $member['name'], $this->code($member['type']), $this->cell($member['description']));
            }

            $lines[] = '';
        }

        return $lines;
    }

    /** @return list<string> */
    private function fieldValues(): array
    {
        $lines = [
            '## Field values',
            '',
            'A field reaches a template as a `FieldView`, from `$page->field(\'handle\')` or a card’s `$item->field(\'handle\')`. It prints as its text.',
            '',
            '| `type` | `value` | `text` | Empty when |',
            '|---|---|---|---|',
        ];

        foreach (FieldViews::TYPES as $type => $row) {
            $lines[] = sprintf('| `%s` | `%s` | %s | %s |', $type, $this->code($row['value']), $this->cell($row['text']), $this->cell($row['empty']));
        }

        return [...$lines, ''];
    }

    /** @return list<string> */
    private function components(ViewDataCatalogue $catalogue): array
    {
        $lines = ['## Components', ''];

        foreach ($catalogue->components() as $component) {
            $lines[] = '### `<x-teme::'.$component['name'].'>`';
            $lines[] = '';
            $lines[] = $this->cell($component['description']);
            $lines[] = '';

            if ($component['attributes'] === []) {
                $lines[] = 'No attributes.';
                $lines[] = '';

                continue;
            }

            $lines[] = '| Attribute | Type | Default | Description |';
            $lines[] = '|---|---|---|---|';

            foreach ($component['attributes'] as $attribute) {
                $lines[] = sprintf('| `%s` | `%s` | %s | %s |', $attribute['name'], $this->code($attribute['type']), $this->cell($attribute['default']), $this->cell($attribute['description']));
            }

            $lines[] = '';
        }

        return $lines;
    }

    /** A table cell: a `|` is escaped, as GenerateFieldsReference does. */
    private function cell(string $text): string
    {
        return str_replace('|', '\|', $text);
    }

    /** Code in a table cell: a `|` is escaped, and no backtick can end the code early. */
    private function code(string $text): string
    {
        return str_replace('|', '\|', str_replace('`', "'", $text));
    }
}
